package tunnel

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/url"
	"strings"
)

// GenerateSecureToken 使用 CSPRNG 生成 32 字节（64 位十六进制）高熵加密安全 Token
func GenerateSecureToken() (string, error) {
	bytes := make([]byte, 32)
	if _, err := rand.Read(bytes); err != nil {
		return "", fmt.Errorf("failed to read cryptographically secure random bytes: %w", err)
	}
	return hex.EncodeToString(bytes), nil
}

// FormatPublicURL 将基础公网 URL 与鉴权 Token 格式化为一键免密秒登 URL
func FormatPublicURL(baseURL, token string) string {
	baseURL = strings.TrimSpace(baseURL)
	if baseURL == "" {
		return ""
	}

	token = strings.TrimSpace(token)
	if token == "" {
		return baseURL
	}

	// 规范化 URL 结构
	parsed, err := url.Parse(baseURL)
	if err != nil {
		separator := "?"
		if strings.Contains(baseURL, "?") {
			separator = "&"
		}
		return fmt.Sprintf("%s%stoken=%s", baseURL, separator, url.QueryEscape(token))
	}

	if parsed.Path == "" {
		parsed.Path = "/"
	}

	q := parsed.Query()
	q.Set("token", token)
	parsed.RawQuery = q.Encode()

	return parsed.String()
}

// EnsureTunnelSecurity 确保公网隧道模式下不会裸奔；若未配置 Token 则自动生成
func EnsureTunnelSecurity(tunnelEnabled bool, existingToken string) (string, bool, error) {
	existingToken = strings.TrimSpace(existingToken)
	if !tunnelEnabled {
		return existingToken, false, nil
	}

	if existingToken != "" {
		return existingToken, false, nil
	}

	token, err := GenerateSecureToken()
	if err != nil {
		return "", false, err
	}

	return token, true, nil
}

// FormatBanner 返回终端高亮展示的公网直达访问卡片
func FormatBanner(publicURL, token string, autoGenerated bool) string {
	loginURL := FormatPublicURL(publicURL, token)
	var sb strings.Builder

	sb.WriteString("\n┌────────────────────────────────────────────────────────────────────────────┐\n")
	sb.WriteString("│                        tmux-ui Cloudflare Tunnel Ready                     │\n")
	sb.WriteString("├────────────────────────────────────────────────────────────────────────────┤\n")
	if autoGenerated {
		sb.WriteString("│ [SECURITY] No auth token provided; auto-generated random 256-bit token!   │\n")
	}
	if loginURL != "" {
		sb.WriteString(fmt.Sprintf("│ One-Click Public Login: %-51s│\n", loginURL))
	}
	if token != "" {
		sb.WriteString(fmt.Sprintf("│ Secret Auth Token:     %-51s│\n", token))
	}
	sb.WriteString("└────────────────────────────────────────────────────────────────────────────┘\n")

	return sb.String()
}
